// $apply — aggregation, grouping, and pre-filtering.
//
// Spec source:
//   https://learn.microsoft.com/en-us/power-apps/developer/data-platform/webapi/query/aggregate-data
//
// Canonical pipeline shape (in order of execution):
//
//   $apply=filter(<predicate>)/groupby((<col>[, <col>]),aggregate(<agg>[, <agg>]))
//          └─ stage 1 ─────┘ └─ stage 2 ──────────┘ └─ stage 3 ───────────┘
//                                                    optional w/ groupby
//
// Or one of the degenerate forms:
//   $apply=aggregate(<agg>[, <agg>])                  → single-row aggregate
//   $apply=groupby((<col>[, <col>]))                  → distinct values
//   $apply=filter(<predicate>)/groupby((<col>))       → distinct values w/ pre-filter
//
// Per the doc, each <agg> takes one of these shapes:
//   <col> with sum     as <alias>
//   <col> with average as <alias>
//   <col> with min     as <alias>
//   <col> with max     as <alias>
//   $count as <alias>    ← row count — pseudo-column, no "with"
//
// Per the "OData aggregation limitations" section:
//   • countdistinct (CountColumn in FetchXml) is NOT supported in OData.
//   • $orderby with aggregate values is not supported.
//   • groupby on DateTime is not supported.
//   • Hard 50,000-row cap on the input set.
//
// Pre-filter lives inside the pipeline as
// `filter(<predicate>)`. The predicate is the same OData $filter expression
// shape used by the top-level $filter — so we reuse the existing FilterEditor
// component for the editing surface. Encoding is delegated to
// `groupToOData(prefilter, table)`.

